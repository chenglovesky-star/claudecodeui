/**
 * Sanitize a path component to prevent shell injection.
 * Only allow alphanumeric, hyphens, underscores, dots, and forward slashes.
 */
function safePath(p) {
  return p.replace(/[^a-zA-Z0-9_\-./]/g, '_');
}

/**
 * Generate a unique heredoc delimiter that doesn't collide with file content.
 */
function uniqueDelimiter(base, content) {
  let delim = base;
  let i = 0;
  while (content.includes(delim)) {
    i++;
    delim = `${base}_${i}`;
  }
  return delim;
}

/**
 * Generate a macOS .command installation script.
 */
function generateMacScript(commands, skills, mcpServers) {
  const lines = [];
  lines.push('#!/bin/bash');
  lines.push('# Claude CLI Skill Pack Installer (macOS)');
  lines.push('# Generated by Claude Code UI');
  lines.push('set -e');
  lines.push('');
  lines.push('CLAUDE_DIR="$HOME/.claude"');
  lines.push('COMMANDS_DIR="$CLAUDE_DIR/commands"');
  lines.push('SKILLS_DIR="$CLAUDE_DIR/skills"');
  lines.push('');
  lines.push('echo "========================================="');
  lines.push('echo "  Claude CLI Skill Pack Installer"');
  lines.push('echo "========================================="');
  lines.push('echo ""');
  lines.push('command_added=0');
  lines.push('command_skipped=0');
  lines.push('skill_added=0');
  lines.push('skill_skipped=0');
  lines.push('');

  // --- Proxy Config ---
  lines.push('echo "----- 代理配置 -----"');
  lines.push('echo "请选择使用模式:"');
  lines.push('echo "  1) 登录号 / 拼车"');
  lines.push('echo "  2) 中转站"');
  lines.push('');
  lines.push('PROXY_MODE=""');
  lines.push('for _i in 1 2 3; do');
  lines.push('  read -rp "输入选项 [1/2]: " _mode_input');
  lines.push('  if [ "$_mode_input" = "1" ] || [ "$_mode_input" = "2" ]; then');
  lines.push('    PROXY_MODE="$_mode_input"');
  lines.push('    break');
  lines.push('  fi');
  lines.push('  echo "  错误：请输入 1 或 2"');
  lines.push('done');
  lines.push('if [ -z "$PROXY_MODE" ]; then');
  lines.push('  echo "输入无效，已退出。"');
  lines.push('  exit 1');
  lines.push('fi');
  lines.push('');
  lines.push('# Collect base URL and API key (中转站 only)');
  lines.push('ANTHROPIC_BASE_URL=""');
  lines.push('ANTHROPIC_API_KEY=""');
  lines.push('if [ "$PROXY_MODE" = "2" ]; then');
  lines.push('  for _i in 1 2 3; do');
  lines.push('    read -rp "请输入 Base URL (例: https://api.wow3.top): " _url_input');
  lines.push('    case "$_url_input" in');
  lines.push('      http://*|https://*) ANTHROPIC_BASE_URL="$_url_input"; break ;;');
  lines.push('      *) echo "  错误：Base URL 必须以 http:// 或 https:// 开头" ;;');
  lines.push('    esac');
  lines.push('  done');
  lines.push('  if [ -z "$ANTHROPIC_BASE_URL" ]; then');
  lines.push('    echo "Base URL 无效，已退出。"');
  lines.push('    exit 1');
  lines.push('  fi');
  lines.push('  for _i in 1 2 3; do');
  lines.push('    read -rp "请输入 API Key: " _key_input');
  lines.push('    if [ -n "$_key_input" ]; then');
  lines.push('      ANTHROPIC_API_KEY="$_key_input"');
  lines.push('      break');
  lines.push('    fi');
  lines.push('    echo "  错误：API Key 不能为空"');
  lines.push('  done');
  lines.push('  if [ -z "$ANTHROPIC_API_KEY" ]; then');
  lines.push('    echo "API Key 无效，已退出。"');
  lines.push('    exit 1');
  lines.push('  fi');
  lines.push('fi');
  lines.push('');
  lines.push('# Collect proxy address');
  lines.push('PROXY_URL=""');
  lines.push('for _i in 1 2 3; do');
  lines.push('  read -rp "请输入代理地址 (http://ip:port): " _proxy_input');
  lines.push('  case "$_proxy_input" in');
  lines.push('    http://*) PROXY_URL="$_proxy_input"; break ;;');
  lines.push('    *) echo "  错误：代理地址必须以 http:// 开头" ;;');
  lines.push('  esac');
  lines.push('done');
  lines.push('if [ -z "$PROXY_URL" ]; then');
  lines.push('  echo "代理地址无效，已退出。"');
  lines.push('  exit 1');
  lines.push('fi');
  lines.push('');
  lines.push('# Write to ~/.claude/settings.json via python3');
  lines.push('if ! command -v python3 &>/dev/null; then');
  lines.push('  echo "  ✗ 未找到 python3，无法写入代理配置，已退出。"');
  lines.push('  exit 1');
  lines.push('else');
  lines.push(`python3 -c "
import json, os, sys

proxy_url = sys.argv[1]
mode = sys.argv[2]
base_url = sys.argv[3] if len(sys.argv) > 3 else ''
api_key  = sys.argv[4] if len(sys.argv) > 4 else ''

settings_path = os.path.expanduser('~/.claude/settings.json')
if os.path.exists(settings_path):
    with open(settings_path, 'r') as f:
        settings = json.load(f)
else:
    settings = {}

env = settings.get('env') or {}
settings['env'] = env
env['HTTP_PROXY']  = proxy_url
env['HTTPS_PROXY'] = proxy_url
if mode == '2' and base_url:
    env['ANTHROPIC_BASE_URL'] = base_url
if mode == '2' and api_key:
    env['ANTHROPIC_API_KEY'] = api_key
if 'language' not in settings:
    settings['language'] = '中文'

with open(settings_path, 'w') as f:
    json.dump(settings, f, indent=2, ensure_ascii=False)

print('  ✓ 代理配置已写入 ~/.claude/settings.json')
" "$PROXY_URL" "$PROXY_MODE" "$ANTHROPIC_BASE_URL" "$ANTHROPIC_API_KEY"`);
  lines.push('fi');
  lines.push('');
  lines.push('echo ""');
  lines.push('echo "----- 安装内容 -----"');
  lines.push('');

  // --- Commands ---
  for (const cmd of commands) {
    const relPath = safePath(cmd.relativePath);
    const dir = path.dirname(relPath);
    const delim = uniqueDelimiter('CMD_EOF', cmd.content);
    if (dir && dir !== '.') {
      lines.push(`mkdir -p "$COMMANDS_DIR/${dir}"`);
    } else {
      lines.push('mkdir -p "$COMMANDS_DIR"');
    }
    lines.push(`if [ -f "$COMMANDS_DIR/${relPath}" ]; then`);
    lines.push(`  echo "  ⊘ command (already exists): ${relPath}"`);
    lines.push('  command_skipped=$((command_skipped + 1))');
    lines.push('else');
    lines.push(`  cat > "$COMMANDS_DIR/${relPath}" << '${delim}'`);
    lines.push(cmd.content);
    lines.push(delim);
    lines.push(`  echo "  ✓ command: ${relPath}"`);
    lines.push('  command_added=$((command_added + 1))');
    lines.push('fi');
    lines.push('');
  }

  // --- Skills ---
  for (const skill of skills) {
    const skillName = safePath(skill.name);
    const delim = uniqueDelimiter('SKILL_EOF', skill.content);
    lines.push(`mkdir -p "$SKILLS_DIR/${skillName}"`);
    lines.push(`if [ -f "$SKILLS_DIR/${skillName}/SKILL.md" ]; then`);
    lines.push(`  echo "  ⊘ skill (already exists): ${skillName}"`);
    lines.push('  skill_skipped=$((skill_skipped + 1))');
    lines.push('else');
    lines.push(`  cat > "$SKILLS_DIR/${skillName}/SKILL.md" << '${delim}'`);
    lines.push(skill.content);
    lines.push(delim);
    lines.push(`  echo "  ✓ skill: ${skillName}"`);
    lines.push('  skill_added=$((skill_added + 1))');
    lines.push('fi');
    lines.push('');
  }

  // --- MCP Servers (merge via python3) ---
  if (Object.keys(mcpServers).length > 0) {
    const mcpJson = JSON.stringify(mcpServers);
    const delim = uniqueDelimiter('MCP_EOF', mcpJson);
    lines.push('# Merge MCP server configs into ~/.claude.json');
    lines.push('if ! command -v python3 &>/dev/null; then');
    lines.push('  echo "  ⚠ python3 not found, skipping MCP config merge"');
    lines.push('  echo "    You can manually add MCP servers to ~/.claude.json"');
    lines.push('else');
    lines.push(`MERGE_JSON=$(cat << '${delim}'`);
    lines.push(mcpJson);
    lines.push(`${delim}`);
    lines.push(')');
    lines.push('');
    lines.push(`python3 -c "
import json, os, sys

merge = json.loads(sys.argv[1])
config_path = os.path.expanduser('~/.claude.json')

if os.path.exists(config_path):
    with open(config_path, 'r') as f:
        config = json.load(f)
else:
    config = {}

servers = config.setdefault('mcpServers', {})
added = 0
skipped = 0
for name, cfg in merge.items():
    if name not in servers:
        servers[name] = cfg
        added += 1
        print(f'  ✓ mcp: {name}')
    else:
        skipped += 1
        print(f'  ⊘ mcp (already exists): {name}')

with open(config_path, 'w') as f:
    json.dump(config, f, indent=2, ensure_ascii=False)

print(f'  MCP: {added} added, {skipped} skipped')
" "$MERGE_JSON"`);
    lines.push('fi');
    lines.push('');
  }

  // --- Summary ---
  lines.push('echo ""');
  lines.push('echo "========================================="');
  lines.push('echo "  安装完成!"');
  lines.push('echo "========================================="');
  lines.push('if [ "$PROXY_MODE" = "1" ]; then');
  lines.push('  echo "  模式:     登录号/拼车"');
  lines.push('else');
  lines.push('  echo "  模式:     中转站"');
  lines.push('fi');
  lines.push('echo "  代理:     ${PROXY_URL}"');
  lines.push('echo "  Commands: ${command_added} added, ${command_skipped} skipped"');
  lines.push('echo "  Skills:   ${skill_added} added, ${skill_skipped} skipped"');
  lines.push(`echo "  MCP:      ${Object.keys(mcpServers).length}"`);
  lines.push('echo ""');
  lines.push('echo "请重启 Claude CLI 使配置生效。"');
  lines.push('');

  return lines.join('\n');
}

/**
 * Generate a Windows .bat installation script.
 * Uses embedded Base64-encoded PowerShell for UTF-8 file writing and JSON merging.
 */
function generateWindowsScript(commands, skills, mcpServers) {
  // Build a PowerShell script that does everything
  const psLines = [];
  psLines.push('$ErrorActionPreference = "Stop"');
  psLines.push('$claudeDir = Join-Path $env:USERPROFILE ".claude"');
  psLines.push('$commandsDir = Join-Path $claudeDir "commands"');
  psLines.push('$skillsDir = Join-Path $claudeDir "skills"');
  psLines.push('');
  psLines.push('Write-Host "========================================="');
  psLines.push('Write-Host "  Claude CLI Skill Pack Installer"');
  psLines.push('Write-Host "========================================="');
  psLines.push('Write-Host ""');
  psLines.push('$commandAdded = 0; $commandSkipped = 0');
  psLines.push('$skillAdded = 0; $skillSkipped = 0');
  psLines.push('');

  // --- Proxy Config ---
  psLines.push('Write-Host "----- 代理配置 -----"');
  psLines.push('Write-Host "请选择使用模式:"');
  psLines.push('Write-Host "  1) 登录号 / 拼车"');
  psLines.push('Write-Host "  2) 中转站"');
  psLines.push('');
  psLines.push('$proxyMode = ""');
  psLines.push('for ($i = 0; $i -lt 3; $i++) {');
  psLines.push('  $modeInput = Read-Host "输入选项 [1/2]"');
  psLines.push('  if ($modeInput -eq "1" -or $modeInput -eq "2") { $proxyMode = $modeInput; break }');
  psLines.push('  Write-Host "  错误：请输入 1 或 2"');
  psLines.push('}');
  psLines.push('if ($proxyMode -eq "") { Write-Host "输入无效，已退出。"; exit 1 }');
  psLines.push('');
  psLines.push('$anthropicBaseUrl = ""');
  psLines.push('$anthropicApiKey = ""');
  psLines.push('if ($proxyMode -eq "2") {');
  psLines.push('  for ($i = 0; $i -lt 3; $i++) {');
  psLines.push('    $urlInput = Read-Host "请输入 Base URL (例: https://api.wow3.top)"');
  psLines.push('    if ($urlInput -match "^https?://") { $anthropicBaseUrl = $urlInput; break }');
  psLines.push('    Write-Host "  错误：Base URL 必须以 http:// 或 https:// 开头"');
  psLines.push('  }');
  psLines.push('  if ($anthropicBaseUrl -eq "") { Write-Host "Base URL 无效，已退出。"; exit 1 }');
  psLines.push('  for ($i = 0; $i -lt 3; $i++) {');
  psLines.push('    $keyInput = Read-Host "请输入 API Key"');
  psLines.push('    if ($keyInput -ne "") { $anthropicApiKey = $keyInput; break }');
  psLines.push('    Write-Host "  错误：API Key 不能为空"');
  psLines.push('  }');
  psLines.push('  if ($anthropicApiKey -eq "") { Write-Host "API Key 无效，已退出。"; exit 1 }');
  psLines.push('}');
  psLines.push('');
  psLines.push('$proxyUrl = ""');
  psLines.push('for ($i = 0; $i -lt 3; $i++) {');
  psLines.push('  $proxyInput = Read-Host "请输入代理地址 (http://ip:port)"');
  psLines.push('  if ($proxyInput -match "^http://") { $proxyUrl = $proxyInput; break }');
  psLines.push('  Write-Host "  错误：代理地址必须以 http:// 开头"');
  psLines.push('}');
  psLines.push('if ($proxyUrl -eq "") { Write-Host "代理地址无效，已退出。"; exit 1 }');
  psLines.push('');
  psLines.push('# Write proxy config to %USERPROFILE%\\.claude\\settings.json');
  psLines.push('$settingsPath = Join-Path $env:USERPROFILE ".claude\\settings.json"');
  psLines.push('if (Test-Path $settingsPath) {');
  psLines.push('  $settings = Get-Content $settingsPath -Raw | ConvertFrom-Json');
  psLines.push('} else {');
  psLines.push('  $settings = [PSCustomObject]@{}');
  psLines.push('}');
  psLines.push('if (-not ($settings.PSObject.Properties.Name -contains "env") -or $settings.env -eq $null) {');
  psLines.push('  if ($settings.PSObject.Properties.Name -contains "env") {');
  psLines.push('    $settings.env = [PSCustomObject]@{}');
  psLines.push('  } else {');
  psLines.push('    $settings | Add-Member -NotePropertyName "env" -NotePropertyValue ([PSCustomObject]@{})');
  psLines.push('  }');
  psLines.push('}');
  psLines.push('$envObj = $settings.env');
  psLines.push('foreach ($key in @("HTTP_PROXY", "HTTPS_PROXY")) {');
  psLines.push('  if ($envObj.PSObject.Properties.Name -contains $key) {');
  psLines.push('    $envObj.$key = $proxyUrl');
  psLines.push('  } else {');
  psLines.push('    $envObj | Add-Member -NotePropertyName $key -NotePropertyValue $proxyUrl');
  psLines.push('  }');
  psLines.push('}');
  psLines.push('if ($proxyMode -eq "2") {');
  psLines.push('  $extraPairs = @(@("ANTHROPIC_BASE_URL", $anthropicBaseUrl), @("ANTHROPIC_API_KEY", $anthropicApiKey))');
  psLines.push('  foreach ($pair in $extraPairs) {');
  psLines.push('    $k = $pair[0]; $v = $pair[1]');
  psLines.push('    if ($envObj.PSObject.Properties.Name -contains $k) {');
  psLines.push('      $envObj.$k = $v');
  psLines.push('    } else {');
  psLines.push('      $envObj | Add-Member -NotePropertyName $k -NotePropertyValue $v');
  psLines.push('    }');
  psLines.push('  }');
  psLines.push('}');
  psLines.push('if (-not ($settings.PSObject.Properties.Name -contains "language")) {');
  psLines.push('  $settings | Add-Member -NotePropertyName "language" -NotePropertyValue "中文"');
  psLines.push('}');
  psLines.push('$settingsDir = Split-Path $settingsPath');
  psLines.push('if (-not (Test-Path $settingsDir)) { New-Item -ItemType Directory -Path $settingsDir -Force | Out-Null }');
  psLines.push('$settings | ConvertTo-Json -Depth 10 | Set-Content $settingsPath -Encoding UTF8');
  psLines.push('Write-Host "  OK 代理配置已写入 settings.json"');
  psLines.push('');
  psLines.push('Write-Host ""');
  psLines.push('Write-Host "----- 安装内容 -----"');
  psLines.push('');

  // --- Commands ---
  for (const cmd of commands) {
    const dir = path.dirname(cmd.relativePath);
    const winPath = cmd.relativePath.replace(/\//g, '\\');
    const encoded = Buffer.from(cmd.content, 'utf-8').toString('base64');
    if (dir && dir !== '.') {
      const winDir = dir.replace(/\//g, '\\');
      psLines.push(`$d = Join-Path $commandsDir "${winDir}"`);
    } else {
      psLines.push('$d = $commandsDir');
    }
    psLines.push('if (-not (Test-Path $d)) { New-Item -ItemType Directory -Path $d -Force | Out-Null }');
    psLines.push(`$commandPath = Join-Path $commandsDir "${winPath}"`);
    psLines.push('if (Test-Path $commandPath) {');
    psLines.push(`  Write-Host "  SKIP command (already exists): ${cmd.relativePath}"`);
    psLines.push('  $commandSkipped++');
    psLines.push('} else {');
    psLines.push(`  $bytes = [Convert]::FromBase64String("${encoded}")`);
    psLines.push('  [System.IO.File]::WriteAllBytes($commandPath, $bytes)');
    psLines.push(`  Write-Host "  OK command: ${cmd.relativePath}"`);
    psLines.push('  $commandAdded++');
    psLines.push('}');
    psLines.push('');
  }

  // --- Skills ---
  for (const skill of skills) {
    const encoded = Buffer.from(skill.content, 'utf-8').toString('base64');
    psLines.push(`$sd = Join-Path $skillsDir "${skill.name}"`);
    psLines.push('if (-not (Test-Path $sd)) { New-Item -ItemType Directory -Path $sd -Force | Out-Null }');
    psLines.push('$skillPath = Join-Path $sd "SKILL.md"');
    psLines.push('if (Test-Path $skillPath) {');
    psLines.push(`  Write-Host "  SKIP skill (already exists): ${skill.name}"`);
    psLines.push('  $skillSkipped++');
    psLines.push('} else {');
    psLines.push(`  $bytes = [Convert]::FromBase64String("${encoded}")`);
    psLines.push('  [System.IO.File]::WriteAllBytes($skillPath, $bytes)');
    psLines.push(`  Write-Host "  OK skill: ${skill.name}"`);
    psLines.push('  $skillAdded++');
    psLines.push('}');
    psLines.push('');
  }

  // --- MCP Servers ---
  if (Object.keys(mcpServers).length > 0) {
    const mcpJsonEscaped = JSON.stringify(mcpServers).replace(/'/g, "''");
    psLines.push('# Merge MCP configs');
    psLines.push(`$mergeJson = '${mcpJsonEscaped}'`);
    psLines.push('$configPath = Join-Path $env:USERPROFILE ".claude.json"');
    psLines.push('if (Test-Path $configPath) {');
    psLines.push('  $config = Get-Content $configPath -Raw | ConvertFrom-Json');
    psLines.push('} else {');
    psLines.push('  $config = [PSCustomObject]@{}');
    psLines.push('}');
    psLines.push('if (-not ($config.PSObject.Properties.Name -contains "mcpServers")) {');
    psLines.push('  $config | Add-Member -NotePropertyName "mcpServers" -NotePropertyValue ([PSCustomObject]@{})');
    psLines.push('}');
    psLines.push('$merge = $mergeJson | ConvertFrom-Json');
    psLines.push('$added = 0; $skipped = 0');
    psLines.push('foreach ($prop in $merge.PSObject.Properties) {');
    psLines.push('  if (-not ($config.mcpServers.PSObject.Properties.Name -contains $prop.Name)) {');
    psLines.push('    $config.mcpServers | Add-Member -NotePropertyName $prop.Name -NotePropertyValue $prop.Value');
    psLines.push('    $added++');
    psLines.push('    Write-Host "  OK mcp: $($prop.Name)"');
    psLines.push('  } else {');
    psLines.push('    $skipped++');
    psLines.push('    Write-Host "  SKIP mcp (already exists): $($prop.Name)"');
    psLines.push('  }');
    psLines.push('}');
    psLines.push('$config | ConvertTo-Json -Depth 10 | Set-Content $configPath -Encoding UTF8');
    psLines.push('Write-Host "  MCP: $added added, $skipped skipped"');
    psLines.push('');
  }

  // --- Summary ---
  psLines.push('Write-Host ""');
  psLines.push('Write-Host "========================================="');
  psLines.push('Write-Host "  安装完成!"');
  psLines.push('Write-Host "========================================="');
  psLines.push('if ($proxyMode -eq "1") {');
  psLines.push('  Write-Host "  模式:     登录号/拼车"');
  psLines.push('} else {');
  psLines.push('  Write-Host "  模式:     中转站"');
  psLines.push('}');
  psLines.push('Write-Host "  代理:     $proxyUrl"');
  psLines.push('Write-Host "  Commands: $commandAdded added, $commandSkipped skipped"');
  psLines.push('Write-Host "  Skills:   $skillAdded added, $skillSkipped skipped"');
  psLines.push(`Write-Host "  MCP:      ${Object.keys(mcpServers).length}"`);
  psLines.push('Write-Host ""');
  psLines.push('Write-Host "请重启 Claude CLI 使配置生效。"');

  const psScript = psLines.join('\r\n');
  const psBase64 = Buffer.from(psScript, 'utf16le').toString('base64');

  // Wrap in a .bat file that invokes the encoded PowerShell
  const batLines = [];
  batLines.push('@echo off');
  batLines.push('REM Claude CLI Skill Pack Installer (Windows)');
  batLines.push('REM Generated by Claude Code UI');
  batLines.push('');
  batLines.push(`powershell -NoProfile -ExecutionPolicy Bypass -EncodedCommand ${psBase64}`);
  batLines.push('');
  batLines.push('pause');

  return batLines.join('\r\n');
}

